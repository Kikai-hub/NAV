using UnityEngine;
using NAV.World.Generation;

namespace NAV.Dev
{
    /// <summary>
    /// TEMPORARY (see WeaponArsenal): once the world has a spawn point, places one WeaponRack
    /// per WeaponArsenal rack in a half ring in front of it, snapped to the ground and facing the
    /// spawn. Delete together with WeaponArsenal when the weapons get resources and recipes.
    /// </summary>
    public class WeaponArsenalSpawner : MonoBehaviour
    {
        [SerializeField] private WorldGenerator _worldGenerator;
        [SerializeField] private WeaponArsenal _arsenal;
        [SerializeField] private WeaponRack _rackPrefab;
        [SerializeField, Min(1f)] private float _radius = 7f;
        [Tooltip("Arc the racks are spread over, centred on +Z from the spawn point.")]
        [SerializeField, Range(30f, 360f)] private float _arcDegrees = 200f;
        [SerializeField] private LayerMask _groundLayers = ~0;

        private bool _spawned;

        private void Awake()
        {
            if (_worldGenerator == null || _arsenal == null || _rackPrefab == null)
            {
                Debug.LogError($"{nameof(WeaponArsenalSpawner)} on '{name}' is missing a required reference (WorldGenerator/Arsenal/RackPrefab).", this);
                enabled = false;
            }
        }

        // Polled rather than evented: WorldGenerator has no "generated" event, and the world is
        // generated by SaveManager at startup (new game or load).
        private void Update()
        {
            if (_spawned || !_worldGenerator.HasSpawnPoint)
            {
                return;
            }

            _spawned = true;
            Spawn(_worldGenerator.SpawnPoint);
            enabled = false;
        }

        private void Spawn(Vector3 center)
        {
            int count = _arsenal.Racks.Count;
            for (int i = 0; i < count; i++)
            {
                WeaponArsenal.Rack rack = _arsenal.Racks[i];
                float t = count > 1 ? (float)i / (count - 1) : 0.5f;
                float angle = (-_arcDegrees * 0.5f + _arcDegrees * t) * Mathf.Deg2Rad;
                Vector3 position = center + new Vector3(Mathf.Sin(angle), 0f, Mathf.Cos(angle)) * _radius;

                if (Physics.Raycast(position + Vector3.up * 50f, Vector3.down, out RaycastHit hit, 100f, _groundLayers, QueryTriggerInteraction.Ignore))
                {
                    position = hit.point;
                }

                Vector3 toCenter = center - position;
                toCenter.y = 0f;
                Quaternion rotation = toCenter.sqrMagnitude > 0.01f ? Quaternion.LookRotation(toCenter) : Quaternion.identity;

                WeaponRack instance = Instantiate(_rackPrefab, position, rotation, transform);
                instance.name = $"WeaponRack ({rack.Title})";
                instance.Configure(rack.Title, rack.Items);
            }

            Debug.Log($"{nameof(WeaponArsenalSpawner)}: placed {count} temporary weapon racks around the spawn point.", this);
        }
    }
}
