using System;
using System.Collections.Generic;
using System.IO;
using UnityEngine;

namespace NAV.Core.Save
{
    /// <summary>
    /// Plain file I/O for save games (JsonUtility, one file per save slot under
    /// Application.persistentDataPath/Saves/) plus the small bit of state that has to survive a
    /// scene load (MainMenu -> gameplay scene) without a DontDestroyOnLoad object: which save (if
    /// any) is pending a load, and which save id/seed the current play session is writing
    /// autosaves to. Static fields survive SceneManager.LoadScene within the same Play session
    /// (they only reset on a fresh domain reload, i.e. actually stopping Play or a build restart),
    /// which is the whole point here - see SaveManager, the only thing that reads/writes these.
    ///
    /// A static class, not a MonoBehaviour/singleton - nothing here needs a GameObject or a
    /// per-frame Update, so a persistent scene object would just be unnecessary global state (see
    /// CLAUDE.md's Architecture Rules).
    /// </summary>
    public static class SaveSystem
    {
        private const string SaveFolderName = "Saves";
        private const string BackupSuffix = ".bak";
        private const string TempSuffix = ".tmp";

        /// <summary>Version of the SaveGameData layout. Bump it when a field is renamed, removed
        /// or changes meaning, and add the matching step to Migrate. Adding a new field with a safe
        /// default doesn't need a bump - JsonUtility leaves it at its default for older files.</summary>
        public const int FormatVersion = 1;

        /// <summary>Version of world generation. The world isn't stored, it's regenerated from
        /// the seed, so ANY change that moves terrain or resources for the same seed (code in
        /// WorldGenerator, values in a WorldGenerationSettings or BiomeDefinition asset) must
        /// bump this. Older saves then still load, but SaveManager treats their depleted resource
        /// ids as invalid and lifts the player back onto the ground, and the Load list warns that
        /// buildings may be out of place.</summary>
        public const int WorldGenerationVersion = 2; // 2: birch groves inside forests (2026-10-22)

        /// <summary>Set by MainMenuUIController's Load list before loading the gameplay scene;
        /// null means "start a new game instead". SaveManager reads and immediately clears this
        /// on Start.</summary>
        public static string PendingLoadSaveId { get; set; }

        /// <summary>Name/seed chosen on the Create World screen, set together right before the
        /// gameplay scene loads (only meaningful when PendingLoadSaveId is null). SaveManager
        /// reads and immediately clears PendingNewGameName on Start, same pattern as
        /// PendingLoadSaveId - an empty/null name means "no Create World screen was used" (e.g.
        /// testing the gameplay scene directly), which SaveManager falls back to a fully random
        /// seed and a default name for.</summary>
        public static string PendingNewGameName { get; set; }
        public static int PendingNewGameSeed { get; set; }

        /// <summary>The save slot this play session's autosaves overwrite. Set once by
        /// SaveManager (new random id for a new game, or the loaded save's own id) and never
        /// changed after - this is what makes "the world saves into its own old save" true: every
        /// autosave targets the same file.</summary>
        public static string CurrentSaveId { get; set; }

        public static int CurrentSeed { get; set; }
        public static string CurrentWorldName { get; set; }

        private static string SaveFolder => Path.Combine(Application.persistentDataPath, SaveFolderName);

        public static void Save(SaveGameData data)
        {
            if (data == null || string.IsNullOrEmpty(data.SaveId))
            {
                Debug.LogError($"{nameof(SaveSystem)}.Save was called with no SaveId - refusing to write an unaddressable file.");
                return;
            }

            // The world being saved was always generated by this build, even when it was loaded
            // from an outdated save - so a re-save is current again.
            data.FormatVersion = FormatVersion;
            data.WorldGenerationVersion = WorldGenerationVersion;

            Directory.CreateDirectory(SaveFolder);
            string json = JsonUtility.ToJson(data, true);
            string path = GetPath(data.SaveId);
            string tempPath = path + TempSuffix;
            string backupPath = path + BackupSuffix;

            // Crash-safe write: the new save goes to a temp file first, then replaces the real one
            // in a single step that keeps the previous save as .bak. A crash mid-write leaves at
            // worst a broken .tmp - the real file and its backup are never half-written.
            File.WriteAllText(tempPath, json);
            if (File.Exists(path))
            {
                try
                {
                    File.Replace(tempPath, path, backupPath);
                    return;
                }
                catch (Exception e) when (e is PlatformNotSupportedException || e is IOException)
                {
                    // File.Replace isn't available on every platform/file system - fall back to
                    // copy-then-move, which still never leaves the real file half-written.
                    Debug.LogWarning($"{nameof(SaveSystem)}: File.Replace failed ({e.Message}), using copy fallback.");
                    File.Copy(path, backupPath, true);
                    File.Delete(path);
                }
            }

            File.Move(tempPath, path);
        }

        /// <summary>Permanently deletes one save (with its backup). Safe to call with an id that
        /// doesn't exist (no-op) - callers don't need to check File.Exists themselves first.</summary>
        public static void DeleteSave(string saveId)
        {
            string path = GetPath(saveId);
            foreach (string file in new[] { path, path + BackupSuffix, path + TempSuffix })
            {
                if (File.Exists(file))
                {
                    File.Delete(file);
                }
            }
        }

        /// <summary>Reads a save, falling back to its .bak copy when the main file is missing or
        /// unreadable. Returns null (and logs) if neither can be read, or if the save was written
        /// by a newer build of the game.</summary>
        public static SaveGameData Load(string saveId)
        {
            string path = GetPath(saveId);
            SaveGameData data = ReadWithBackup(path);
            if (data == null)
            {
                Debug.LogError($"{nameof(SaveSystem)}: no readable save file for id '{saveId}' at '{path}'.");
                return null;
            }

            if (IsFromNewerGame(data))
            {
                Debug.LogError($"{nameof(SaveSystem)}: save '{saveId}' has format version {data.FormatVersion}, this build only knows up to {FormatVersion} - not loading it.");
                return null;
            }

            return data;
        }

        /// <summary>True when the save was written by a newer build (format this build can't
        /// read safely). The Load list shows it but doesn't let it load.</summary>
        public static bool IsFromNewerGame(SaveGameData data)
        {
            return data.FormatVersion > FormatVersion;
        }

        /// <summary>True when the save was made with a different world generation than this
        /// build's (see WorldGenerationVersion) - the terrain under its buildings may differ.</summary>
        public static bool IsWorldGenerationOutdated(SaveGameData data)
        {
            return data.WorldGenerationVersion != WorldGenerationVersion;
        }

        /// <summary>Brings an older save's data up to the current FormatVersion. Each future bump
        /// adds one "if (data.FormatVersion &lt; N)" step here, applied in order.</summary>
        private static void Migrate(SaveGameData data)
        {
            if (data.FormatVersion < 1)
            {
                // Saves from before versioning: the layout is identical, only the version fields
                // are missing. Their world generation is unknown - it was the only one that existed
                // then, i.e. version 1.
                data.WorldGenerationVersion = 1;
                data.FormatVersion = 1;
            }
        }

        /// <summary>Main file first, then its .bak - also covers a crash in Save's copy fallback
        /// between deleting the old file and moving the new one in (only .bak/.tmp left).</summary>
        private static SaveGameData ReadWithBackup(string path)
        {
            SaveGameData data = TryRead(path);
            if (data != null)
            {
                return data;
            }

            data = TryRead(path + BackupSuffix);
            if (data != null)
            {
                Debug.LogWarning($"{nameof(SaveSystem)}: '{path}' is missing or unreadable - using its backup.");
            }

            return data;
        }

        private static SaveGameData TryRead(string file)
        {
            if (!File.Exists(file))
            {
                return null;
            }

            try
            {
                SaveGameData data = JsonUtility.FromJson<SaveGameData>(File.ReadAllText(file));
                // A truncated/garbage file can parse into an empty object - no SaveId means unusable.
                if (data == null || string.IsNullOrEmpty(data.SaveId))
                {
                    Debug.LogError($"{nameof(SaveSystem)}: save file '{file}' has no SaveId - treating it as corrupt.");
                    return null;
                }

                Migrate(data);
                return data;
            }
            catch (Exception e)
            {
                // Logged loudly per CLAUDE.md's Error Handling rule; the caller decides whether a
                // backup can stand in.
                Debug.LogError($"{nameof(SaveSystem)}: failed to read save file '{file}': {e.Message}");
                return null;
            }
        }

        /// <summary>All saves on disk, newest first - what MainMenu's Load list displays.</summary>
        public static List<SaveGameData> ListSaves()
        {
            var result = new List<SaveGameData>();
            if (!Directory.Exists(SaveFolder))
            {
                return result;
            }

            // Every save is "<id>.json" and/or "<id>.json.bak"; collect the ids from both so a save
            // whose main file was lost still shows up through its backup.
            var paths = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            foreach (string file in Directory.GetFiles(SaveFolder, "*.json"))
            {
                paths.Add(file);
            }
            foreach (string file in Directory.GetFiles(SaveFolder, "*.json" + BackupSuffix))
            {
                paths.Add(file.Substring(0, file.Length - BackupSuffix.Length));
            }

            foreach (string path in paths)
            {
                // One corrupt file shouldn't hide every other save - TryRead logs it and this one
                // is skipped (or replaced by its backup).
                SaveGameData data = ReadWithBackup(path);
                if (data != null)
                {
                    result.Add(data);
                }
            }

            result.Sort((a, b) => b.SavedAtUnixSeconds.CompareTo(a.SavedAtUnixSeconds));
            return result;
        }

        private static string GetPath(string saveId)
        {
            return Path.Combine(SaveFolder, saveId + ".json");
        }
    }
}
